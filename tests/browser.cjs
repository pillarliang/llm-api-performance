const {chromium} = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');

(async()=>{
  const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  const origin=process.env.PREVIEW_ORIGIN||'http://127.0.0.1:8001';
  await page.goto(origin);
  await page.locator('#workspace').waitFor({state:'visible'});
  await page.waitForFunction(()=>document.querySelector('#stat-models').textContent!=='—');
  assert.equal(await page.locator('#login').count(),0);
  const config=(await(await page.request.get(origin+'/api/config')).json()).config;
  const enabled=config.models.filter(m=>m.enabled!==false),groups=config.tasks.length*config.input_tokens.length*config.concurrencies.length*enabled.reduce((n,m)=>n+m.profiles.length,0);
  assert.equal(await page.locator('#stat-models').textContent(),String(enabled.length));
  assert.equal(await page.locator('#stat-groups').textContent(),String(groups));
  await page.locator('#check-plan').click();
  await page.waitForFunction(()=>!document.getElementById('start-run').disabled);
  assert.ok(Number(await page.locator('#pending-calls').textContent())<=groups*config.repetitions);
  await page.locator('#model-0').uncheck();
  assert.equal(await page.locator('#stat-models').textContent(),String(enabled.length-1));
  assert.equal(await page.locator('#start-run').isDisabled(),true);
  await page.locator('#model-0').check();
  await page.locator('#toggle-yaml').click();
  await page.locator('#yaml-editor').waitFor({state:'visible'});
  const yaml=await page.locator('#yaml-editor').inputValue();
  assert.ok(yaml.includes('base_url:'));
  assert.ok(!/sk-[A-Za-z0-9_.-]{20,}/.test(yaml));
  await page.locator('#apply-yaml').click();
  await page.locator('#yaml-panel').waitFor({state:'hidden'});
  await page.screenshot({path:'/workspace/.qa/desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
  await page.screenshot({path:'/workspace/.qa/mobile.png',fullPage:true});
  await page.locator('[data-tab="history"]').click();
  assert.ok(await page.locator('#history').isVisible());
  await page.locator('[data-tab="results"]').click();
  assert.ok(await page.locator('#results').isVisible());
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('Browser: no-login access, config, plan, model/profile selection, YAML, desktop/mobile layout and tabs passed.');
})().catch(error=>{console.error(error);process.exit(1)});
