const {chromium}=require('playwright');
const assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
 const page=await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true});
 const errors=[];page.on('pageerror',error=>errors.push(error.message));
 const origin=process.env.PREVIEW_ORIGIN||'http://127.0.0.1:8001';
 await page.goto(origin+'/#catalog');
 await page.waitForFunction(()=>document.querySelectorAll('#catalog-rows tr').length>0,{}, {timeout:60000});
 const data=await(await page.request.get(origin+'/api/models')).json();
 assert.equal(await page.locator('#catalog-rows tr').count(),data.count);
 assert.equal(await page.locator('#login').count(),0);
 for(const id of ['glm-5.3','glm-5.2','qwen3.8-max'])assert.ok(data.models.some(m=>m.id===id));
 await page.locator('#catalog-focus').selectOption('glm53');
 assert.ok(await page.locator('#catalog-rows tr').count()>0);
 for(const id of await page.locator('#catalog-rows td:first-child').allTextContents())assert.match(id,/glm-?5\.3/i);
 await page.locator('#catalog-focus').selectOption('all');
 await page.locator('#catalog-search').fill('glm-5.3-prime');
 const row=page.locator('#catalog-rows tr').first();
 assert.equal(await row.locator('td').first().textContent(),'glm-5.3-prime');
 await row.getByRole('button',{name:'加入实验',exact:true}).click();
 assert.equal(await row.getByRole('button',{name:'已加入',exact:true}).isDisabled(),true);
 await page.locator('[data-tab="experiment"]').click();
 const added=page.locator('#model-list .model-row').filter({hasText:'glm-5.3-prime'});
 assert.equal(await added.locator('.model-title input').isChecked(),false);
 await page.locator('[data-tab="catalog"]').click();
 await page.locator('#catalog-search').fill('');
 const downloadPromise=page.waitForEvent('download');await page.locator('#download-models').click();
 const download=await downloadPromise;await download.saveAs('/workspace/.qa/endpoint-models.json');
 await page.screenshot({path:'/workspace/.qa/catalog.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 assert.deepEqual(errors,[]);
 await browser.close();console.log(`Model catalog: ${data.count} models; no-login, focus filter, search, add-to-experiment and JSON export passed.`);
})().catch(error=>{console.error(error);process.exit(1)});
